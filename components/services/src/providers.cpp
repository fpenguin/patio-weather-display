// Transactional snapshots are larger than the worker stack. Construct them
// directly in PSRAM on the device, and fail without touching output if the
// allocation cannot be satisfied. This also avoids large `value = {}` stack
// temporaries generated by the target compiler.
template <typename T>
class SnapshotScratch {
public:
    SnapshotScratch() {
#ifdef ESP_PLATFORM
        void* storage = heap_caps_malloc(sizeof(T), MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT);
#else
        void* storage = std::malloc(sizeof(T));
#endif
        if (storage) value_ = new (storage) T{};
    }
    ~SnapshotScratch() {
        if (value_) {
            value_->~T();
            std::free(value_);
        }
    }
    SnapshotScratch(const SnapshotScratch&) = delete;
    SnapshotScratch& operator=(const SnapshotScratch&) = delete;
    explicit operator bool() const { return value_ != nullptr; }
    T& get() { return *value_; }
private:
    T* value_{nullptr};
};

