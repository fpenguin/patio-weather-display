#!/usr/bin/env python3
"""Generate a bounded embedded IANA transition table from a compiled zoneinfo tree.

The committed table is IANA 2026f and covers 2024-01-01 through 2038-01-01.
Run after compiling a newer IANA release with zic; see README.md.
"""

from __future__ import annotations

import argparse
import datetime as dt
from pathlib import Path
from zoneinfo import ZoneInfo

START = dt.datetime(2024, 1, 1, tzinfo=dt.timezone.utc)
END = dt.datetime(2038, 1, 1, tzinfo=dt.timezone.utc)
STEP = dt.timedelta(hours=6)


def zone_files(root: Path):
    ignored = {"localtime", "posixrules", "leapseconds", "tzdata.zi", "zone.tab", "zone1970.tab"}
    for path in sorted(p for p in root.rglob("*") if p.is_file()):
        name = path.relative_to(root).as_posix()
        if name in ignored or name.startswith(("posix/", "right/")) or name.startswith("."):
            continue
        yield name, path


def state(zone: ZoneInfo, instant: dt.datetime):
    local = instant.astimezone(zone)
    return int(local.utcoffset().total_seconds()), bool(local.dst()), local.tzname() or "UTC"


def exact_transition(zone: ZoneInfo, before: dt.datetime, after: dt.datetime, old_state):
    lo = int(before.timestamp())
    hi = int(after.timestamp())
    while lo + 1 < hi:
        middle = (lo + hi) // 2
        if state(zone, dt.datetime.fromtimestamp(middle, dt.timezone.utc)) == old_state:
            lo = middle
        else:
            hi = middle
    instant = dt.datetime.fromtimestamp(hi, dt.timezone.utc)
    return hi, state(zone, instant)


def transitions(path: Path):
    with path.open("rb") as source:
        zone = ZoneInfo.from_file(source)
    result = [(int(START.timestamp()), state(zone, START))]
    previous_time = START
    previous_state = result[0][1]
    cursor = START + STEP
    while cursor <= END:
        current_state = state(zone, min(cursor, END - dt.timedelta(seconds=1)))
        if current_state != previous_state:
            when, new_state = exact_transition(zone, previous_time, cursor, previous_state)
            result.append((when, new_state))
            previous_state = new_state
        previous_time = cursor
        cursor += STEP
    return result


def cpp_string(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("zoneinfo", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--version", default="unknown")
    args = parser.parse_args()

    zones = []
    abbreviations = {"UTC"}
    all_transitions = []
    for name, path in zone_files(args.zoneinfo):
        try:
            entries = transitions(path)
        except (ValueError, OSError):
            continue
        first = len(all_transitions)
        for when, (offset, daylight, abbreviation) in entries:
            abbreviations.add(abbreviation)
            all_transitions.append((when, offset, abbreviation, daylight))
        zones.append((name, first, len(entries)))

    abbreviation_list = sorted(abbreviations)
    abbreviation_index = {value: index for index, value in enumerate(abbreviation_list)}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8") as out:
        out.write("// Generated by scripts/generate_tzdb.py; do not edit.\n")
        out.write(f"// IANA tzdata {args.version}; UTC window 2024-01-01..2038-01-01.\n")
        out.write('#include "tzdb_generated.hpp"\n\nnamespace patio::tzdb {\n\n')
        out.write("const char* const kAbbreviations[] = {\n")
        for value in abbreviation_list:
            out.write(f'    "{cpp_string(value)}",\n')
        out.write("};\nconst std::size_t kAbbreviationCount = sizeof(kAbbreviations) / sizeof(kAbbreviations[0]);\n\n")
        out.write("const Transition kTransitions[] = {\n")
        for when, offset, abbreviation, daylight in all_transitions:
            out.write(f"    {{{when}LL, {offset}, {abbreviation_index[abbreviation]}, {1 if daylight else 0}}},\n")
        out.write("};\nconst std::size_t kTransitionCount = sizeof(kTransitions) / sizeof(kTransitions[0]);\n\n")
        out.write("const Zone kZones[] = {\n")
        for name, first, count in zones:
            out.write(f'    {{"{cpp_string(name)}", {first}, {count}}},\n')
        out.write("};\nconst std::size_t kZoneCount = sizeof(kZones) / sizeof(kZones[0]);\n\n}  // namespace patio::tzdb\n")

    print(f"generated {len(zones)} zones, {len(all_transitions)} transitions, "
          f"{len(abbreviation_list)} abbreviations -> {args.output}")


if __name__ == "__main__":
    main()
