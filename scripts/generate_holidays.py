#!/usr/bin/env python3
"""Generate the flash-resident holiday index. Requires holidays==0.108."""
from datetime import date, timedelta
from pathlib import Path
import json
import holidays

if holidays.__version__ != "0.108":
    raise SystemExit("Install holidays==0.108 to reproduce this release")
first, last = 2026, 2036
years = range(first - 1, last + 2)  # Include New Year's Day observed in December.
territories = {"AS", "GU", "MP", "PR", "UM", "VI"}
states = sorted((name, code) for name, code in holidays.US().subdivisions_aliases.items()
                if code not in territories)
assert len(states) == 51
provinces = sorted((name, code) for name, code in holidays.CA().subdivisions_aliases.items()
                   if name in {
                       "Alberta", "British Columbia", "Manitoba", "New Brunswick",
                       "Newfoundland and Labrador", "Nova Scotia", "Northwest Territories",
                       "Nunavut", "Ontario", "Prince Edward Island", "Quebec",
                       "Saskatchewan", "Yukon",
                   })
assert len(provinces) == 13
catalog = [("KR", "South Korea", None), ("FED", "US (federal)", None)]
catalog += [(code, name, None) for name, code in states]
catalog += [("BOS", "Boston, MA", "MA"), ("DEN", "Denver, CO", "CO"),
            ("NYC", "New York City, NY", "NY")]
us_end = len(catalog)
catalog += [(f"C-{code}", name, None) for name, code in provinces]

def short(name):
    name = name.replace("Juneteenth National Independence Day", "Juneteenth")
    name = name.replace("Korean New Year", "Seollal").replace("The day preceding ", "Eve of ")
    name = name.replace("The second day of ", "Day after ").replace("Alternative holiday for ", "Substitute: ")
    # Dashboard features one holiday; retain a whole name on coincidence.
    return name if len(name.encode()) < 64 else name.split("; ")[0]

def city_dates(code):
    events = {}
    for year in range(first, last + 1):
        if code == "BOS":
            for month, day, name in [(3, 17, "Evacuation Day"), (6, 17, "Bunker Hill Day")]:
                d = date(year, month, day)
                events[d] = (name, False)
                if d.weekday() == 6:
                    events[d + timedelta(days=1)] = (name + " (observed)", False)
            d = date(year, 10, 8)
            events[d + timedelta(days=-d.weekday() % 7)] = ("Indigenous Peoples Day", True)
        elif code == "DEN":
            d = date(year, 3, 31)
            events[d - timedelta(days=d.weekday())] = ("Sí, Se Puede Day", True)
            d = date(year, 10, 8)
            events[d + timedelta(days=-d.weekday() % 7)] = ("Indigenous Peoples' Day", True)
        elif code == "NYC":
            d = date(year, 11, 2)  # Tuesday after the first Monday.
            events[d + timedelta(days=(1-d.weekday()) % 7)] = ("Election Day", True)
            events[date(year, 2, 12)] = ("Lincoln's Birthday (floating)", False)
    return events

rows, names, descriptors = [], {}, []
for code, label, parent in catalog:
    if parent:
        events = city_dates(code)  # Overrides only; look up the state and federal layers separately.
    else:
        if code == "KR":
            h = holidays.KR(years=years, language="en_US")
        elif code.startswith("C-"):
            h = holidays.CA(subdiv=code[2:], years=years, language="en_CA")
        else:
            h = holidays.US(subdiv=None if code == "FED" else code,
                            years=years, language="en_US")
        events = {d: (short(n), True) for d, n in h.items()}
        if code == "CA":
            events = {d: (n.replace("Cesar Chavez Day", "Farmworkers Day"), off)
                      for d, (n, off) in events.items()}
    start = len(rows)
    for d, (name, off) in sorted(events.items()):
        if first <= d.year <= last:
            assert len(name.encode()) < 64, name
            nid = names.setdefault(name, len(names))
            rows.append(((d.year-first)*512 + d.month*32 + d.day, nid, off))
    descriptors.append((code, label, parent or "", start, len(rows)))
assert len(rows) < 65536 and len(names) < 256
out = ["// Generated by scripts/generate_holidays.py; see third_party/python-holidays/LICENSE.",
       f"constexpr int first_year = {first}, last_year = {last};",
       "constexpr const char* event_names[] = {"]
out += [json.dumps(n, ensure_ascii=False) + "," for n in names]
out += ["};", "constexpr DateEntry dates[] = {"]
for i in range(0, len(rows), 8):
    out.append(" ".join("{%d,%d,%d}," % r for r in rows[i:i+8]))
out += ["};", "constexpr Calendar calendars[] = {"]
out += ['{"%s","%s","%s",%d,%d},' % d for d in descriptors]
out += ["};",
        f"constexpr std::size_t us_begin = 1, us_end = {us_end};",
        f"constexpr std::size_t canada_begin = {us_end};",
        "constexpr char us_options[] = " +
        json.dumps("\n".join(d[1] for d in descriptors[1:us_end])) + ";",
        "constexpr char canada_options[] = " +
        json.dumps("Canada (federal)\n" + "\n".join(d[1] for d in descriptors[us_end:])) + ";"]
target = Path(__file__).resolve().parents[1]/"components/weather_core/src/holiday_data.inc"
target.write_text("\n".join(out)+"\n")
print(f"{len(rows)} dates, {len(names)} names, {len(catalog)} calendars")
