class UrlWriter {
public:
    UrlWriter(char* output, std::size_t capacity) : output_(output), capacity_(capacity) {
        if (output_ && capacity_ > 0) output_[0] = '\0';
    }

    bool append(const char* value) {
        std::size_t length = 0;
        if (!bounded_length(value, 2048, length)) return fail();
        return append(value, length);
    }

    bool append(const char* value, std::size_t length) {
        if (!good_ || !output_ || capacity_ == 0 || length >= capacity_ - used_) {
            return fail();
        }
        std::memcpy(output_ + used_, value, length);
        used_ += length;
        output_[used_] = '\0';
        return true;
    }

    bool append_format(const char* format, ...) {
        char buffer[96]{};
        va_list arguments;
        va_start(arguments, format);
        const int count = std::vsnprintf(buffer, sizeof(buffer), format, arguments);
        va_end(arguments);
        if (count < 0 || static_cast<std::size_t>(count) >= sizeof(buffer)) return fail();
        return append(buffer, static_cast<std::size_t>(count));
    }

    bool append_encoded(const char* value, std::size_t maximum = kMaxInputTextLength) {
        std::size_t length = 0;
        if (!bounded_length(value, maximum, length)) return fail();
        constexpr char kHex[] = "0123456789ABCDEF";
        for (std::size_t i = 0; i < length; ++i) {
            const auto character = static_cast<unsigned char>(value[i]);
            const bool unreserved =
                (character >= 'A' && character <= 'Z') ||
                (character >= 'a' && character <= 'z') ||
                (character >= '0' && character <= '9') || character == '-' ||
                character == '.' || character == '_' || character == '~';
            if (unreserved) {
                const char raw = static_cast<char>(character);
                if (!append(&raw, 1)) return false;
            } else {
                char encoded[3] = {'%', kHex[character >> 4U], kHex[character & 0x0FU]};
                if (!append(encoded, sizeof(encoded))) return false;
            }
        }
        return true;
    }

    bool good() const { return good_; }

private:
    bool fail() {
        good_ = false;
        used_ = 0;
        if (output_ && capacity_ > 0) output_[0] = '\0';
        return false;
    }

    char* output_{nullptr};
    std::size_t capacity_{0};
    std::size_t used_{0};
    bool good_{true};
};

bool valid_coordinates(double latitude, double longitude) {
    return std::isfinite(latitude) && std::isfinite(longitude) && latitude >= -90.0 &&
           latitude <= 90.0 && longitude >= -180.0 && longitude <= 180.0;
}

bool normalized_country_code(const char* country,
                             bool uppercase,
                             char (&normalized)[3]) {
    std::size_t length = 0;
    if (!bounded_length(country, 2, length) || length != 2) return false;
    for (std::size_t i = 0; i < 2; ++i) {
        const auto character = static_cast<unsigned char>(country[i]);
        if (!std::isalpha(character)) return false;
        normalized[i] = static_cast<char>(uppercase ? std::toupper(character)
                                                    : std::tolower(character));
    }
    normalized[2] = '\0';
    return true;
}

void assign_country_code(Text<3>& output, const char* country) {
    char normalized[3]{};
    if (normalized_country_code(country, true, normalized)) {
        output.assign(normalized);
    } else {
        output.assign(nullptr);
    }
}

bool decimal_string(const char* text, double& value) {
    std::size_t length = 0;
    if (!bounded_length(text, 32, length) || length == 0) return false;
    char buffer[33]{};
    std::memcpy(buffer, text, length);
    char* end = nullptr;
    value = std::strtod(buffer, &end);
    return end == buffer + length && std::isfinite(value);
}

bool coordinate_value(const cJSON* object, const char* name, double& value) {
    const cJSON* item = member(object, name);
    if (cJSON_IsNumber(item) && std::isfinite(item->valuedouble)) {
        value = item->valuedouble;
        return true;
    }
    return cJSON_IsString(item) && item->valuestring && decimal_string(item->valuestring, value);
}

const char* first_string(const cJSON* object,
                         const char* first,
                         const char* second = nullptr,
                         const char* third = nullptr,
                         const char* fourth = nullptr,
                         const char* fifth = nullptr) {
    const char* names[] = {first, second, third, fourth, fifth};
    for (const char* name : names) {
        if (!name) continue;
        const char* value = string_value(object, name);
        if (value && *value) return value;
    }
    return nullptr;
}

void compose_display_name(Location& location, const char* primary) {
    if (!location.display_name.empty()) return;
    char display[80]{};
    const char* city = primary && *primary ? primary : location.city.c_str();
    if (!city) city = "";
    std::size_t used = 0;
    const auto append = [&display, &used](const char* value) {
        if (!value || used >= sizeof(display) - 1) return;
        const std::size_t available = sizeof(display) - 1 - used;
        const std::size_t length = strnlen(value, available);
        std::memcpy(display + used, value, length);
        used += length;
        display[used] = '\0';
    };
    append(city);
    if (!location.region.empty()) {
        append(", ");
        append(location.region.c_str());
    }
    if (!location.country.empty()) {
        append(", ");
        append(location.country.c_str());
    }
    location.display_name.assign(display);
}

bool parse_open_meteo_candidate(const cJSON* item, LocationCandidate& candidate) {
    if (!cJSON_IsObject(item)) return false;
    const char* name = string_value(item, "name");
    double latitude = 0.0;
    double longitude = 0.0;
    if (!name || !coordinate_value(item, "latitude", latitude) ||
        !coordinate_value(item, "longitude", longitude) ||
        !valid_coordinates(latitude, longitude)) {
        return false;
    }

    candidate = {};
    candidate.provider = LocationProvider::OpenMeteo;
    candidate.location.latitude = latitude;
    candidate.location.longitude = longitude;
    candidate.location.city.assign(name);
    candidate.location.region.assign(string_value(item, "admin1"));
    candidate.location.country.assign(string_value(item, "country"));
    candidate.location.time_zone.assign(string_value(item, "timezone"));
    assign_country_code(candidate.location.country_code, string_value(item, "country_code"));
    compose_display_name(candidate.location, name);

    std::int64_t id = 0;
    if (int64_value(item, "id", id)) {
        char id_text[32]{};
        std::snprintf(id_text, sizeof(id_text), "%lld", static_cast<long long>(id));
        candidate.provider_id.assign(id_text);
    }
    const cJSON* postcodes = member(item, "postcodes");
    if (cJSON_IsArray(postcodes)) {
        const cJSON* postcode = cJSON_GetArrayItem(postcodes, 0);
        if (cJSON_IsString(postcode) && postcode->valuestring) {
            candidate.postal_code.assign(postcode->valuestring);
        }
    }
    return true;
}

bool parse_nominatim_candidate(const cJSON* item, LocationCandidate& candidate) {
    if (!cJSON_IsObject(item)) return false;
    double latitude = 0.0;
    double longitude = 0.0;
    if (!coordinate_value(item, "lat", latitude) ||
        !coordinate_value(item, "lon", longitude) ||
        !valid_coordinates(latitude, longitude)) {
        return false;
    }

    candidate = {};
    candidate.provider = LocationProvider::Nominatim;
    candidate.location.latitude = latitude;
    candidate.location.longitude = longitude;
    candidate.location.display_name.assign(string_value(item, "display_name"));

    const cJSON* address = member(item, "address");
    const char* name = string_value(item, "name");
    if (cJSON_IsObject(address)) {
        candidate.location.city.assign(first_string(address, "city", "town", "village",
                                                    "municipality", "hamlet"));
        if (candidate.location.city.empty()) {
            candidate.location.city.assign(first_string(address, "suburb", "county"));
        }
        candidate.location.region.assign(first_string(address, "state", "region"));
        candidate.location.country.assign(string_value(address, "country"));
        assign_country_code(candidate.location.country_code,
                            string_value(address, "country_code"));
        candidate.postal_code.assign(string_value(address, "postcode"));
    }
    if (candidate.location.city.empty()) candidate.location.city.assign(name);
    compose_display_name(candidate.location, name);

    const char* string_id = first_string(item, "postcode_id", "osm_id");
    if (string_id) {
        candidate.provider_id.assign(string_id);
    } else {
        std::int64_t place_id = 0;
        if (int64_value(item, "place_id", place_id)) {
            char id_text[32]{};
            std::snprintf(id_text, sizeof(id_text), "%lld",
                          static_cast<long long>(place_id));
            candidate.provider_id.assign(id_text);
        }
    }
    return true;
}

double degrees_to_radians(double degrees) {
    constexpr double kPi = 3.14159265358979323846;
    return degrees * kPi / 180.0;
}

double haversine_km(double first_latitude,
                    double first_longitude,
                    double second_latitude,
                    double second_longitude) {
    constexpr double kEarthMeanRadiusKm = 6371.0088;
    const double latitude_delta = degrees_to_radians(second_latitude - first_latitude);
    const double longitude_delta = degrees_to_radians(second_longitude - first_longitude);
    const double first_latitude_rad = degrees_to_radians(first_latitude);
    const double second_latitude_rad = degrees_to_radians(second_latitude);
    const double sin_latitude = std::sin(latitude_delta / 2.0);
    const double sin_longitude = std::sin(longitude_delta / 2.0);
    const double haversine = sin_latitude * sin_latitude +
                             std::cos(first_latitude_rad) *
                                 std::cos(second_latitude_rad) *
                                 sin_longitude * sin_longitude;
    return 2.0 * kEarthMeanRadiusKm *
           std::asin(std::sqrt(std::clamp(haversine, 0.0, 1.0)));
}

bool parse_aqhi_community(const cJSON* feature,
                          double target_latitude,
                          double target_longitude,
                          AqhiCommunity& community) {
    const cJSON* geometry = member(feature, "geometry");
    const cJSON* coordinates = member(geometry, "coordinates");
    const cJSON* properties = member(feature, "properties");
    const char* id = string_value(properties, "location_id");
    const char* name = string_value(properties, "location_name_en");
    if (!cJSON_IsArray(coordinates) || cJSON_GetArraySize(coordinates) < 2 || !id || !name) {
        return false;
    }
    const cJSON* longitude_item = cJSON_GetArrayItem(coordinates, 0);
    const cJSON* latitude_item = cJSON_GetArrayItem(coordinates, 1);
    if (!cJSON_IsNumber(longitude_item) || !cJSON_IsNumber(latitude_item) ||
        !valid_coordinates(latitude_item->valuedouble, longitude_item->valuedouble)) {
        return false;
    }

    community = {};
    community.id.assign(id);
    community.name.assign(name);
    community.administrative_zone.assign(
        first_string(properties, "eccc_administrative-zone_name_en",
                     "eccc_administrative-zone"));
    community.latitude = latitude_item->valuedouble;
    community.longitude = longitude_item->valuedouble;
    community.distance_km = haversine_km(target_latitude, target_longitude,
                                         community.latitude, community.longitude);
    return std::isfinite(community.distance_km);
}

void retain_nearest(AqhiCommunityList& list, const AqhiCommunity& candidate) {
    std::size_t position = 0;
    while (position < list.count &&
           list.communities[position].distance_km <= candidate.distance_km) {
        ++position;
    }

    if (list.count < list.communities.size()) {
        for (std::size_t index = list.count; index > position; --index) {
            list.communities[index] = list.communities[index - 1];
        }
        list.communities[position] = candidate;
        ++list.count;
        return;
    }

    list.source_had_more = true;
    if (position >= list.communities.size()) return;
    for (std::size_t index = list.communities.size() - 1; index > position; --index) {
        list.communities[index] = list.communities[index - 1];
    }
    list.communities[position] = candidate;
}

