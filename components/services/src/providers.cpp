ParseResult parse_eccc_aqhi(const char* json,
                            std::size_t length,
                            std::int64_t fetched_time_utc,
                            const char* expected_community_id,
                            AirQualitySnapshot& output) {
    std::size_t community_length = 0;
    if (!bounded_length(expected_community_id, 15, community_length) || community_length == 0) {
        return result(ParseCode::NullArgument, "An explicit AQHI community id is required");
    }

    cJSON* raw_root = nullptr;
    ParseResult parsed = parse_document(json, length, kMaxAqhiResponseBytes, raw_root);
    if (!parsed) return parsed;
    JsonDocument document(raw_root);
    const cJSON* features = member(document.get(), "features");
    if (!cJSON_IsArray(features)) {
        return result(ParseCode::InvalidSchema, "ECCC AQHI features array is missing");
    }

    const cJSON* selected = nullptr;
    std::int64_t selected_time = std::numeric_limits<std::int64_t>::min();
    bool selected_latest = false;
    const int feature_count = cJSON_GetArraySize(features);
    for (int index = 0; index < feature_count; ++index) {
        const cJSON* feature = cJSON_GetArrayItem(features, index);
        const cJSON* properties = member(feature, "properties");
        const char* location_id = string_value(properties, "location_id");
        if (!location_id || std::strcmp(location_id, expected_community_id) != 0) continue;

        std::int64_t observation_time = 0;
        const char* observed = string_value(properties, "observation_datetime");
        if (!observed || !parse_rfc3339(observed, observation_time)) continue;
        const bool latest = cJSON_IsTrue(member(properties, "latest"));
        if (!selected || (latest && !selected_latest) ||
            (latest == selected_latest && observation_time > selected_time)) {
            selected = properties;
            selected_time = observation_time;
            selected_latest = latest;
        }
    }
    if (!selected) {
        return result(ParseCode::CommunityNotFound,
                      "Expected ECCC AQHI community was not in the response");
    }

    AirQualitySnapshot snapshot{};
    snapshot.scale.assign("Canadian AQHI");
    snapshot.community_id.assign(expected_community_id);
    snapshot.community.assign(string_value(selected, "location_name_en"));
    snapshot.status.fetched_time_utc = fetched_time_utc;
    snapshot.status.source_time_utc = selected_time;

    const cJSON* value = member(selected, "aqhi");
    if (!value || cJSON_IsNull(value)) {
        return result(ParseCode::InvalidSchema,
                      "ECCC observation has no AQHI value");
    }
    if (!cJSON_IsNumber(value) || !std::isfinite(value->valuedouble) ||
        value->valuedouble <= 0.0) {
        return result(ParseCode::InvalidSchema, "ECCC AQHI value is malformed");
    }

    if (value->valuedouble > static_cast<double>(std::numeric_limits<float>::max())) {
        return result(ParseCode::InvalidSchema, "ECCC AQHI value is outside a safe range");
    }
    const float raw = static_cast<float>(value->valuedouble);
    const bool ten_plus = raw > 10.0F;
    const int rounded = ten_plus ? 10 : std::clamp(static_cast<int>(std::lround(raw)), 1, 10);
    snapshot.raw_aqhi = Optional<float>::some(raw);
    snapshot.display_index = Optional<int>::some(rounded);
    snapshot.display_ten_plus = ten_plus;
    snapshot.category = aqhi_category(rounded, ten_plus);
    const char* notes = string_value(selected, "special_notes_en");
    const char* aqhi_type_value = string_value(selected, "aqhi_type");
    snapshot.official_smoke_supported =
        contains_ignore_case(notes, "wildfire smoke") || contains_ignore_case(notes, "smoke") ||
        contains_ignore_case(aqhi_type_value, "AQHI+") ||
        contains_ignore_case(aqhi_type_value, "smoke");
    snapshot.status.state = SourceState::Fresh;
    snapshot.status.detail.assign("Official ECCC AQHI observation");
    output = snapshot;
    return result(ParseCode::Ok, "OK");
}

ParseResult parse_eccc_alerts(const char* json,
                              std::size_t length,
                              std::int64_t fetched_time_utc,
                              AlertSnapshot& output) {
    cJSON* raw_root = nullptr;
    ParseResult parsed = parse_document(json, length, kMaxAlertsResponseBytes, raw_root);
    if (!parsed) return parsed;
    JsonDocument document(raw_root);
    const cJSON* features = member(document.get(), "features");
    if (!cJSON_IsArray(features)) {
        return result(ParseCode::InvalidSchema, "ECCC alerts features array is missing");
    }

    SnapshotScratch<AlertParserScratch> scratch;
    if (!scratch) return result(ParseCode::OutOfMemory, "Alert snapshot allocation failed");
    auto& snapshot = scratch.get().snapshot;
    snapshot.status.state = SourceState::Fresh;
    snapshot.status.fetched_time_utc = fetched_time_utc;
    std::size_t skipped = 0;
    std::size_t inactive = 0;
    bool bounded = false;

    const int feature_count = cJSON_GetArraySize(features);
    for (int index = 0; index < feature_count; ++index) {
        const cJSON* feature = cJSON_GetArrayItem(features, index);
        const cJSON* properties = member(feature, "properties");
        if (!cJSON_IsObject(feature) || !cJSON_IsObject(properties)) {
            ++skipped;
            continue;
        }

        auto& alert = scratch.get().alert;
        alert.~WeatherAlert();
        new (&alert) WeatherAlert{};
        const char* id = string_value(feature, "id");
        if (!id) id = string_value(properties, "id");
        const char* name = string_value(properties, "alert_name_en");
        if (!id || !name) {
            ++skipped;
            continue;
        }
        alert.id.assign(id);
        alert.feature_id.assign(string_value(properties, "feature_id"));
        alert.code.assign(string_value(properties, "alert_code"));
        alert.name.assign(name);
        alert.short_name.assign(string_value(properties, "alert_short_name_en"));
        alert.text.assign(string_value(properties, "alert_text_en"));
        assign_lowercase(alert.risk_colour, string_value(properties, "risk_colour_en"));
        assign_lowercase(alert.impact, string_value(properties, "impact_en"));
        alert.confidence.assign(string_value(properties, "confidence_en"));
        assign_lowercase(alert.status, string_value(properties, "status_en"));
        alert.type = alert_type(string_value(properties, "alert_type"));
        parse_optional_time(properties, "publication_datetime", alert.published_utc);
        parse_optional_time(properties, "validity_datetime", alert.valid_from_utc);
        parse_optional_time(properties, "event_end_datetime", alert.event_end_utc);
        parse_optional_time(properties, "expiration_datetime", alert.expires_utc);
        const bool cancelled = alert.status == "cancelled" ||
                               alert.status == "canceled" ||
                               alert.status == "ended" ||
                               alert.status == "expired";
        const bool expired = (alert.event_end_utc > 0 &&
                              alert.event_end_utc <= fetched_time_utc) ||
                             (alert.expires_utc > 0 &&
                              alert.expires_utc <= fetched_time_utc);
        if (cancelled || expired) {
            ++inactive;
            continue;
        }

        const char* text = string_value(properties, "alert_text_en");
        alert.identifies_smoke = contains_ignore_case(name, "wildfire smoke") ||
                                 contains_ignore_case(name, "smoke") ||
                                 contains_ignore_case(text, "wildfire smoke");
        alert.identifies_lightning = contains_ignore_case(name, "lightning") ||
                                     contains_ignore_case(name, "thunderstorm") ||
                                     contains_ignore_case(text, "lightning");

        std::size_t duplicate = snapshot.count;
        for (std::size_t existing = 0; existing < snapshot.count; ++existing) {
            if (std::strcmp(snapshot.alerts[existing].id.c_str(), alert.id.c_str()) == 0) {
                duplicate = existing;
                break;
            }
        }
        if (duplicate < snapshot.count) {
            if (alert.published_utc > snapshot.alerts[duplicate].published_utc) {
                snapshot.alerts[duplicate] = alert;
            }
            continue;
        }
        if (snapshot.count >= snapshot.alerts.size()) {
            bounded = true;
            continue;
        }
        snapshot.alerts[snapshot.count++] = alert;
        snapshot.status.source_time_utc =
            std::max(snapshot.status.source_time_utc, alert.published_utc);
    }

    if (feature_count > 0 && snapshot.count == 0 && skipped > 0 && inactive == 0) {
        return result(ParseCode::InvalidSchema,
                      "All ECCC alert records were malformed");
    }
    if (bounded) {
        snapshot.status.detail.assign("ECCC active alerts (bounded to 12 records)");
    } else if (skipped > 0) {
        snapshot.status.detail.assign("ECCC active alerts (malformed records skipped)");
    } else {
        snapshot.status.detail.assign("ECCC current active alerts");
    }
    output = snapshot;
    return result(ParseCode::Ok, "OK");
}

ParseResult parse_network_location_hint(const char* json, std::size_t length, NetworkLocationHint& output) {
    cJSON* root = nullptr;
    auto parsed = parse_document(json, length, kMaxIpHintBytes, root);
    if (!parsed) return parsed;
    JsonDocument doc(root);
    const char* city = string_value(root, "city");
    const char* country = string_value(root, "country");
    const char* code = string_value(root, "country_code");
    auto valid_name = [](const char* name, std::size_t capacity) {
        if (!name || !*name || std::strlen(name) >= capacity) return false;
        bool has_text = false;
        for (const auto* p = reinterpret_cast<const unsigned char*>(name); *p; ++p) {
            if (*p < 32 || *p == 127) return false;
            if (*p != ' ') has_text = true;
        }
        return has_text;
    };
    if (!cJSON_IsTrue(member(root, "success")) || !valid_name(city, output.city.value.size()) ||
        !valid_name(country, output.country.value.size()) || !code || std::strlen(code) != 2 ||
        code[0] < 'A' || code[0] > 'Z' || code[1] < 'A' || code[1] > 'Z')
        return result(ParseCode::InvalidSchema, "No usable network location");
    output.city.assign(city);
    output.country.assign(country);
    output.country_code.assign(code);
    return result(ParseCode::Ok, "OK");
}

ParseResult parse_open_meteo_geocoding(const char* json,
                                       std::size_t length,
                                       LocationCandidateList& output) {
    cJSON* raw_root = nullptr;
    ParseResult parsed = parse_document(json, length, kMaxLocationResponseBytes, raw_root);
    if (!parsed) return parsed;
    JsonDocument document(raw_root);
    const cJSON* root = document.get();
    if (cJSON_IsTrue(member(root, "error"))) {
        return result(ParseCode::InvalidSchema, "Open-Meteo geocoding returned an API error");
    }

    const cJSON* results = member(root, "results");
    if (!results) {
        output.~LocationCandidateList();
        new (&output) LocationCandidateList{};
        return result(ParseCode::Ok, "No geocoding matches");
    }
    if (!cJSON_IsArray(results)) {
        return result(ParseCode::InvalidSchema, "Open-Meteo results is not an array");
    }

    SnapshotScratch<LocationCandidateList> scratch;
    if (!scratch) return result(ParseCode::OutOfMemory, "Location candidate allocation failed");
    auto& candidates = scratch.get();
    std::size_t malformed = 0;
    const int count = cJSON_GetArraySize(results);
    for (int index = 0; index < count; ++index) {
        LocationCandidate candidate{};
        if (!parse_open_meteo_candidate(cJSON_GetArrayItem(results, index), candidate)) {
            ++malformed;
            continue;
        }
        if (candidates.count >= candidates.candidates.size()) {
            candidates.source_had_more = true;
            continue;
        }
        candidates.candidates[candidates.count++] = candidate;
    }
    if (count > 0 && candidates.count == 0 && malformed > 0) {
        return result(ParseCode::InvalidSchema, "All Open-Meteo geocoding matches were malformed");
    }
    output = candidates;
    return result(ParseCode::Ok,
                  malformed > 0 ? "Malformed geocoding matches skipped" : "OK");
}

