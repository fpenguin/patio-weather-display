ParseResult parse_open_meteo_weather(const char* json,
                                     std::size_t length,
                                     std::int64_t fetched_time_utc,
                                     WeatherSnapshot& output) {
    cJSON* raw_root = nullptr;
    ParseResult parsed = parse_document(json, length, kMaxWeatherResponseBytes, raw_root);
    if (!parsed) return parsed;
    JsonDocument document(raw_root);
    const cJSON* root = document.get();

    const cJSON* api_error = member(root, "error");
    if (cJSON_IsTrue(api_error)) {
        return result(ParseCode::InvalidSchema, "Open-Meteo returned an API error");
    }

    const cJSON* hourly = member(root, "hourly");
    const cJSON* times = member(hourly, "time");
    if (!cJSON_IsObject(hourly) || !cJSON_IsArray(times)) {
        return result(ParseCode::InvalidSchema, "Open-Meteo hourly.time is missing");
    }

    const cJSON* rain = nullptr;
    const cJSON* showers = nullptr;
    const cJSON* snowfall = nullptr;
    const cJSON* probability = nullptr;
    const cJSON* temperatures = nullptr;
    const cJSON* apparent = nullptr;
    const cJSON* wind = nullptr;
    const cJSON* gusts = nullptr;
    const cJSON* uv = nullptr;
    const cJSON* codes = nullptr;
    if (!validate_optional_array(hourly, "rain", rain) ||
        !validate_optional_array(hourly, "showers", showers) ||
        !validate_optional_array(hourly, "snowfall", snowfall) ||
        !validate_optional_array(hourly, "precipitation_probability", probability) ||
        !validate_optional_array(hourly, "temperature_2m", temperatures) ||
        !validate_optional_array(hourly, "apparent_temperature", apparent) ||
        !validate_optional_array(hourly, "wind_speed_10m", wind) ||
        !validate_optional_array(hourly, "wind_gusts_10m", gusts) ||
        !validate_optional_array(hourly, "uv_index", uv) ||
        !validate_optional_array(hourly, "weather_code", codes)) {
        return result(ParseCode::InvalidSchema, "Open-Meteo hourly field is not an array");
    }

    const cJSON* units = member(root, "hourly_units");
    if (units && !cJSON_IsObject(units)) {
        return result(ParseCode::InvalidSchema, "Open-Meteo hourly_units is not an object");
    }
    if (!unit_is(units, "rain", "mm") || !unit_is(units, "showers", "mm") ||
        !unit_is(units, "snowfall", "cm") ||
        !unit_is(units, "precipitation_probability", "%") ||
        !unit_is(units, "wind_speed_10m", "km/h") ||
        !unit_is(units, "wind_gusts_10m", "km/h")) {
        return result(ParseCode::UnsupportedUnits, "Open-Meteo response units do not match the model");
    }

    SnapshotScratch<WeatherSnapshot> scratch;
    if (!scratch) return result(ParseCode::OutOfMemory, "Weather snapshot allocation failed");
    auto& snapshot = scratch.get();
    snapshot.provider.assign("Open-Meteo");
    snapshot.status.state = SourceState::Fresh;
    snapshot.status.fetched_time_utc = fetched_time_utc;

    bool schema_error = false;
    const cJSON* current = member(root, "current");
    if (current && !cJSON_IsObject(current)) {
        return result(ParseCode::InvalidSchema, "Open-Meteo current is not an object");
    }
    if (current) {
        snapshot.current_temperature_c = object_float(current, "temperature_2m", schema_error);
        snapshot.current_apparent_c = object_float(current, "apparent_temperature", schema_error);
        snapshot.current_wind_kmh = object_float(current, "wind_speed_10m", schema_error);
        snapshot.current_gust_kmh = object_float(current, "wind_gusts_10m", schema_error);
        snapshot.current_weather_code = object_int(current, "weather_code", schema_error);
        std::int64_t source_time = 0;
        if (int64_value(current, "time", source_time)) snapshot.status.source_time_utc = source_time;
    }
    if (schema_error) {
        return result(ParseCode::InvalidSchema, "Open-Meteo current contains a malformed value");
    }
    if ((snapshot.current_temperature_c.valid &&
         (snapshot.current_temperature_c.value < -150.0F ||
          snapshot.current_temperature_c.value > 100.0F)) ||
        (snapshot.current_apparent_c.valid &&
         (snapshot.current_apparent_c.value < -150.0F ||
          snapshot.current_apparent_c.value > 100.0F)) ||
        (snapshot.current_wind_kmh.valid && snapshot.current_wind_kmh.value < 0.0F) ||
        (snapshot.current_gust_kmh.valid && snapshot.current_gust_kmh.value < 0.0F)) {
        return result(ParseCode::InvalidSchema, "Open-Meteo current value is outside a safe range");
    }

    const int returned_count = cJSON_GetArraySize(times);
    if (returned_count <= 0) {
        return result(ParseCode::InvalidSchema, "Open-Meteo hourly.time is empty");
    }
    const int count = std::min(returned_count, static_cast<int>(snapshot.hours.size()));
    for (int index = 0; index < count; ++index) {
        const cJSON* time = cJSON_GetArrayItem(times, index);
        if (!cJSON_IsNumber(time) || !std::isfinite(time->valuedouble) ||
            std::floor(time->valuedouble) != time->valuedouble ||
            std::fabs(time->valuedouble) > 9007199254740991.0) {
            return result(ParseCode::InvalidSchema, "Open-Meteo hourly timestamp is malformed");
        }
        const auto end = static_cast<std::int64_t>(time->valuedouble);
        HourlyWeather sample{};
        sample.interval_end_utc = end;
        sample.interval_start_utc = end - 3600;
        sample.rain_mm = float_at(rain, index, schema_error);
        sample.showers_mm = float_at(showers, index, schema_error);
        sample.snowfall_cm = float_at(snowfall, index, schema_error);
        sample.precipitation_probability_percent = float_at(probability, index, schema_error);
        sample.temperature_c = float_at(temperatures, index, schema_error);
        sample.apparent_temperature_c = float_at(apparent, index, schema_error);
        sample.wind_kmh = float_at(wind, index, schema_error);
        sample.gust_kmh = float_at(gusts, index, schema_error);
        sample.uv_index = float_at(uv, index, schema_error);
        sample.weather_code = int_at(codes, index, schema_error);
        sample.kind = end <= fetched_time_utc ? HourKind::HistoricalForecast : HourKind::Forecast;
        if (!sane_weather_sample(sample)) {
            return result(ParseCode::InvalidSchema,
                          "Open-Meteo hourly value is outside a safe range");
        }
        snapshot.hours[static_cast<std::size_t>(index)] = sample;
    }
    if (schema_error) {
        return result(ParseCode::InvalidSchema, "Open-Meteo hourly array contains a malformed value");
    }
    snapshot.hour_count = static_cast<std::size_t>(count);
    snapshot.status.detail.assign(returned_count > count
                                      ? "Open-Meteo model data (bounded to 72 hours)"
                                      : "Open-Meteo model data");
    output = snapshot;
    return result(ParseCode::Ok, "OK");
}

bool build_open_meteo_air_url(char* output, std::size_t capacity, double latitude, double longitude) {
    UrlWriter writer(output, capacity);
    if (!valid_coordinates(latitude, longitude)) return false;
    writer.append("https://air-quality-api.open-meteo.com/v1/air-quality");
    writer.append_format("?latitude=%.6f&longitude=%.6f", latitude, longitude);
    writer.append("&current=us_aqi&timeformat=unixtime");
    return writer.good();
}

