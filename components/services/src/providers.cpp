Optional<float> float_at(const cJSON* array, int index, bool& schema_error) {
    if (!array) return Optional<float>::none();
    const cJSON* item = cJSON_GetArrayItem(array, index);
    if (!item || cJSON_IsNull(item)) return Optional<float>::none();
    if (!cJSON_IsNumber(item) || !std::isfinite(item->valuedouble) ||
        item->valuedouble < -static_cast<double>(std::numeric_limits<float>::max()) ||
        item->valuedouble > static_cast<double>(std::numeric_limits<float>::max())) {
        schema_error = true;
        return Optional<float>::none();
    }
    return Optional<float>::some(static_cast<float>(item->valuedouble));
}

