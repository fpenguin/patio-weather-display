bool build_eccc_alerts_url(char* output,
                           std::size_t capacity,
                           double latitude,
                           double longitude) {
    UrlWriter writer(output, capacity);
    if (!valid_coordinates(latitude, longitude)) return false;

    char filter[96]{};
    const int filter_length = std::snprintf(
        filter, sizeof(filter), "INTERSECTS(geometry, POINT(%.6f %.6f))", longitude, latitude);
    if (filter_length < 0 || static_cast<std::size_t>(filter_length) >= sizeof(filter)) return false;

    constexpr const char* kProperties =
        "alert_code,alert_type,alert_name_en,alert_short_name_en,publication_datetime,"
        "expiration_datetime,validity_datetime,event_end_datetime,alert_text_en,"
        "risk_colour_en,confidence_en,impact_en,province,status_en,feature_id";
    writer.append(kEcccApiEndpoint);
    writer.append("/collections/weather-alerts/items?f=json&filter=");
    writer.append_encoded(filter, sizeof(filter) - 1);
    writer.append("&limit=100&skipGeometry=true&properties=");
    writer.append_encoded(kProperties, 512);
    return writer.good();
}

