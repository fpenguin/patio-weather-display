bool sane_weather_sample(const HourlyWeather& sample) {
    const auto non_negative = [](const Optional<float>& value) {
        return !value.valid || value.value >= 0.0F;
    };
    const bool probability_ok = !sample.precipitation_probability_percent.valid ||
                                (sample.precipitation_probability_percent.value >= 0.0F &&
                                 sample.precipitation_probability_percent.value <= 100.0F);
    const bool temperature_ok =
        (!sample.temperature_c.valid ||
         (sample.temperature_c.value >= -150.0F && sample.temperature_c.value <= 100.0F)) &&
        (!sample.apparent_temperature_c.valid ||
         (sample.apparent_temperature_c.value >= -150.0F &&
          sample.apparent_temperature_c.value <= 100.0F));
    return non_negative(sample.rain_mm) && non_negative(sample.showers_mm) &&
           non_negative(sample.snowfall_cm) && non_negative(sample.wind_kmh) &&
           non_negative(sample.gust_kmh) && non_negative(sample.uv_index) && probability_ok &&
           temperature_ok;
}

template <std::size_t N>
void assign_lowercase(Text<N>& output, const char* input) {
    if (!input) {
        output.assign(nullptr);
        return;
    }
    std::array<char, N> normalized{};
    std::size_t index = 0;
    while (index + 1 < N && input[index] != '\0') {
        normalized[index] =
            static_cast<char>(std::tolower(static_cast<unsigned char>(input[index])));
        ++index;
    }
    normalized[index] = '\0';
    output.assign(normalized.data());
}

